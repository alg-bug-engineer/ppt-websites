#!/bin/bash

# =================================================================
# PPT Website 生产环境自动部署脚本
# =================================================================

# 设置变量
APP_NAME="ppt-frontend"
BACKEND_NAME="ppt-backend"
OLD_DEV_NAME="ppt-dev"

echo "----------------------------------------------------"
echo "[1/5] 正在从 GitHub 拉取最新代码..."
echo "----------------------------------------------------"
git pull origin main

echo ""
echo "----------------------------------------------------"
echo "[2/5] 正在安装依赖..."
echo "----------------------------------------------------"
npm install

echo ""
echo "----------------------------------------------------"
echo "[3/5] 正在构建前端生产环境包 (Build)..."
echo "----------------------------------------------------"
# 执行 vue-tsc 检查并进行 vite build
npm run build

echo ""
echo "----------------------------------------------------"
echo "[4/5] 正在清理旧的 PM2 进程..."
echo "----------------------------------------------------"
# 删除旧的开发模式进程
pm2 delete $OLD_DEV_NAME 2>/dev/null
# 重置生产环境进程
pm2 delete $APP_NAME 2>/dev/null
pm2 delete $BACKEND_NAME 2>/dev/null

echo ""
echo "----------------------------------------------------"
echo "[5/5] 启动生产环境服务..."
echo "----------------------------------------------------"

# 1. 启动后端 Node.js 服务
# 生产环境直接运行 server.js，性能更优
pm2 start server.js --name $BACKEND_NAME

# 2. 启动前端预览服务 (Vite Preview)
# 使用 --host 0.0.0.0 允许外部访问，默认端口 4173
pm2 start "npm run preview -- --host 0.0.0.0" --name $APP_NAME

echo ""
echo "===================================================="
echo "部署完成！当前服务状态："
echo "===================================================="
pm2 list
echo "----------------------------------------------------"
echo "前端访问地址: http://ppt.ai-knowledgepoints.cn:4173"
echo "后端 API 地址: http://ppt.ai-knowledgepoints.cn:3001"
echo "===================================================="
